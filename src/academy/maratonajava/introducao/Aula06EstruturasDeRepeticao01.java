package academy.maratonajava.introducao;

public class Aula06EstruturasDeRepeticao01 {
    public static void main(String[] args) {
        int count = 11;
        while(count > 0){
            count--;
            System.out.println(count);
        }

        for(int i = 1; i <= 10; i++){
            System.out.println(i);
        }
    }
}
