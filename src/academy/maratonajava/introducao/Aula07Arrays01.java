package academy.maratonajava.introducao;

public class Aula07Arrays01 {
    public static void main(String[] args) {
        int [] ages = new int[3];
        ages[0] = 10;
        ages[1] = 7;
        ages[2] = 3;
        for (int i = 0; i < 3; i++) {
            System.out.println(ages[i]);
        }
    }
}
